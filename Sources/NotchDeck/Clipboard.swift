import AppKit
import SwiftUI
import Vision

/// 置顶的文字和文件路径总是保存；其余历史默认只在内存里，打开“保存历史”后才写入磁盘。图片始终不落盘。
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    enum Content {
        case text(String)
        case image(NSImage, Data, NSPasteboard.PasteboardType)
        case files([URL])
    }

    struct Item: Identifiable {
        let id: UUID
        let content: Content
        let date: Date
        let sourceName: String
        var isPinned = false
        /// 只有展示和搜索用这段，复制时始终使用完整内容。
        private let textPreview: String
        private static let previewLength = 20_000

        init(id: UUID = UUID(), content: Content, date: Date, sourceName: String, isPinned: Bool = false) {
            self.id = id
            self.content = content
            self.date = date
            self.sourceName = sourceName
            self.isPinned = isPinned
            if case .text(let text) = content {
                textPreview = String(text.trimmingCharacters(in: .whitespacesAndNewlines).prefix(Self.previewLength))
            } else {
                textPreview = ""
            }
        }

        var preview: String {
            switch content {
            case .text: return textPreview
            case .image(let image, _, _): return L("图片 %d×%d", Int(image.size.width), Int(image.size.height))
            case .files(let urls):
                let first = urls.first?.lastPathComponent ?? ""
                return urls.count > 1 ? L("%@ 等 %d 个文件", first, urls.count) : first
            }
        }
    }

    private static let maxItems = 60
    private static let maxImages = 12
    private static let maxImageBytes = 8_000_000
    /// 超过这个大小的文字不记录。历史里的内容必须能完整粘贴回去，所以不做截断。
    private static let maxTextBytes = 1_000_000
    /// 密码管理器等 App 用这些类型标记不应被记录的内容。
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
    ]

    private static let saveHistoryKey = "clipboardSaveHistory"

    private struct SavedItem: Codable {
        let id: UUID
        var text: String?
        var paths: [String]?
        let date: Date
        let sourceName: String
        let isPinned: Bool

        init?(_ item: Item) {
            switch item.content {
            case .text(let value): text = value
            case .files(let urls): paths = urls.map(\.path)
            case .image: return nil
            }
            id = item.id
            date = item.date
            sourceName = item.sourceName
            isPinned = item.isPinned
        }

        var item: Item? {
            let content: Content
            if let text {
                content = .text(text)
            } else if let paths {
                content = .files(paths.map { URL(fileURLWithPath: $0) })
            } else {
                return nil
            }
            return Item(id: id, content: content, date: date, sourceName: sourceName, isPinned: isPinned)
        }
    }

    @Published private(set) var items: [Item] = [] {
        didSet { schedulePersist() }
    }
    @Published var isPaused = false
    @Published var saveHistory: Bool {
        didSet {
            UserDefaults.standard.set(saveHistory, forKey: Self.saveHistoryKey)
            schedulePersist()
        }
    }

    private let pasteboard = NSPasteboard.general
    private let fileURL = Storage.folder.appendingPathComponent("clipboard.json")
    private var lastChange: Int
    private var timer: Timer?
    private var persistWork: DispatchWorkItem?

    private init() {
        lastChange = NSPasteboard.general.changeCount
        saveHistory = UserDefaults.standard.bool(forKey: Self.saveHistoryKey)
        if let data = try? Data(contentsOf: fileURL), let saved = try? JSONDecoder().decode([SavedItem].self, from: data) {
            items = saved.compactMap(\.item)
        }
    }

    private func schedulePersist() {
        persistWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.persistNow() }
        persistWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    func persistNow() {
        persistWork?.cancel()
        persistWork = nil
        let saved = items.filter { saveHistory || $0.isPinned }.compactMap(SavedItem.init)
        guard !saved.isEmpty else {
            try? FileManager.default.removeItem(at: fileURL)
            return
        }
        guard let data = try? JSONEncoder().encode(saved) else { return }
        try? data.write(to: fileURL, options: .atomic)
        // 复制的内容可能敏感，文件只允许当前用户读写。
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }

    func start() {
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard !isPaused, let content = readContent() else { return }
        let app = NSWorkspace.shared.frontmostApplication
        insert(Item(content: content, date: Date(), sourceName: app?.localizedName ?? ""))
    }

    private func readContent() -> Content? {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return nil }

        let fileOptions: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: fileOptions) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return text.utf8.count <= Self.maxTextBytes ? .text(text) : nil
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes, let image = NSImage(data: data) {
                return .image(image, data, type)
            }
        }
        return nil
    }

    /// 新内容排在置顶项之后。
    private var insertionIndex: Int { items.firstIndex { !$0.isPinned } ?? items.endIndex }

    private func insert(_ item: Item) {
        func matches(_ other: Item) -> Bool { Self.isSameContent(other.content, item.content) }
        guard !items.contains(where: { $0.isPinned && matches($0) }) else { return }
        items.removeAll(where: matches)
        items.insert(item, at: insertionIndex)
        trim()
    }

    private static func isSameContent(_ first: Content, _ second: Content) -> Bool {
        switch (first, second) {
        case (.text(let a), .text(let b)): return a == b
        case (.image(_, let a, _), .image(_, let b, _)): return a == b
        case (.files(let a), .files(let b)): return a.map(\.path) == b.map(\.path)
        default: return false
        }
    }

    /// 数量上限只约束未置顶的内容。
    private func trim() {
        var imageCount = 0
        items.removeAll {
            guard !$0.isPinned, case .image = $0.content else { return false }
            imageCount += 1
            return imageCount > Self.maxImages
        }
        let overflow = items.filter { !$0.isPinned }.count - Self.maxItems
        if overflow > 0 { items.removeLast(overflow) }
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        items = items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    func copy(_ item: Item) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(_, let data, let type): pasteboard.setData(data, forType: type)
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        lastChange = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(item, at: item.isPinned ? 0 : insertionIndex)
        Toasts.shared.show(L("已复制"), icon: "doc.on.clipboard")
    }

    /// 在本机识别图片里的文字并复制，不会上传。复制后会和普通内容一样进入历史。
    func copyText(in item: Item) {
        guard case .image(let image, _, _) = item.content,
              let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
        DispatchQueue.global(qos: .userInitiated).async {
            let text = Self.recognizeText(in: cgImage)
            DispatchQueue.main.async {
                guard let text, !text.isEmpty else {
                    Toasts.shared.show(L("没有识别到文字"), icon: "text.viewfinder")
                    return
                }
                self.pasteboard.clearContents()
                self.pasteboard.setString(text, forType: .string)
                Toasts.shared.show(L("已复制识别出的文字"), icon: "text.viewfinder")
            }
        }
    }

    static func recognizeText(in image: CGImage) -> String? {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.recognitionLanguages = ["zh-Hans", "zh-Hant", "en-US", "ja-JP", "ko-KR"]
        request.usesLanguageCorrection = true
        guard (try? VNImageRequestHandler(cgImage: image).perform([request])) != nil else { return nil }
        return request.results?.compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }

    func remove(_ item: Item) { items.removeAll { $0.id == item.id } }

    /// 置顶内容不会被清空，要单独取消置顶或删除。
    func clear() { items.removeAll { !$0.isPinned } }
}

func relativeTime(_ date: Date) -> String {
    let seconds = Int(Date().timeIntervalSince(date))
    if seconds < 60 { return L("刚刚") }
    if seconds < 3600 { return L("%d 分钟前", seconds / 60) }
    if seconds < 86400 { return L("%d 小时前", seconds / 3600) }
    return L("%d 天前", seconds / 86400)
}

struct ClipboardRow: View {
    let item: ClipboardStore.Item
    var showsMeta = true
    var onPin: (() -> Void)?
    let action: () -> Void
    @State private var hovering = false

    /// 首页卡片里只有三行的高度，紧凑模式要用更小的缩略图。
    private var thumbnailSize: CGFloat { showsMeta ? 28 : 20 }

    @ViewBuilder private var thumbnail: some View {
        switch item.content {
        case .text:
            Image(systemName: "text.alignleft").foregroundStyle(Theme.secondary)
        case .image(let image, _, _):
            Image(nsImage: image).resizable().scaledToFill().frame(width: thumbnailSize, height: thumbnailSize)
                .clipShape(RoundedRectangle(cornerRadius: 5, style: .continuous))
        case .files(let urls):
            Image(nsImage: NSWorkspace.shared.icon(forFile: urls.first?.path ?? "/")).resizable().frame(width: thumbnailSize - 2, height: thumbnailSize - 2)
        }
    }

    var body: some View {
        Button(action: action) {
            HStack(spacing: 8) {
                thumbnail.frame(width: thumbnailSize, height: thumbnailSize)
                VStack(alignment: .leading, spacing: 2) {
                    Text(item.preview.replacingOccurrences(of: "\n", with: " "))
                        .font(.system(size: 12))
                        .lineLimit(1)
                    if showsMeta {
                        Text(item.sourceName.isEmpty ? relativeTime(item.date) : "\(item.sourceName) · \(relativeTime(item.date))")
                            .font(.system(size: 10))
                            .foregroundStyle(Theme.secondary)
                            .lineLimit(1)
                    }
                }
                Spacer(minLength: 0)
            }
            .padding(.leading, 8)
            .padding(.trailing, onPin == nil ? 8 : 30)
            .padding(.vertical, showsMeta ? 4 : 2)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(hovering ? Theme.controlHover : Color.clear))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .overlay(alignment: .trailing) {
            if let onPin, hovering || item.isPinned {
                Button(action: onPin) {
                    Image(systemName: item.isPinned ? "pin.fill" : "pin")
                        .font(.system(size: 11))
                        .foregroundStyle(item.isPinned ? Theme.orange : Theme.secondary)
                        .frame(width: 24, height: 24)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .padding(.trailing, 4)
                .help(item.isPinned ? L("取消置顶") : L("置顶"))
            }
        }
        .onHover { hovering = $0 }
    }
}

struct ClipboardPage: View {
    @ObservedObject var model: PanelModel
    @ObservedObject private var store = ClipboardStore.shared
    @State private var query = ""

    private var filtered: [ClipboardStore.Item] {
        let trimmed = query.trimmingCharacters(in: .whitespaces)
        guard !trimmed.isEmpty else { return store.items }
        return store.items.filter { $0.preview.localizedCaseInsensitiveContains(trimmed) }
    }

    private func headerButton(_ title: String, _ symbol: String, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Label(title, systemImage: symbol).font(.system(size: 12))
        }
        .buttonStyle(.plain)
    }

    var body: some View {
        VStack(spacing: 6) {
            PageHeader(title: L("剪贴板"), model: model) {
                HStack(spacing: 12) {
                    HStack(spacing: 4) {
                        Image(systemName: "magnifyingglass").font(.system(size: 11)).foregroundStyle(Theme.secondary)
                        TextField(L("搜索"), text: $query).textFieldStyle(.plain).font(.system(size: 12))
                    }
                    .padding(.horizontal, 8)
                    .frame(width: 170, height: 20)
                    .background(Capsule().fill(Theme.control))
                    headerButton(store.isPaused ? L("继续记录") : L("暂停记录"), store.isPaused ? "play.fill" : "pause.fill") {
                        store.isPaused.toggle()
                    }
                    headerButton(L("保存历史"), store.saveHistory ? "checkmark.circle.fill" : "circle") {
                        store.saveHistory.toggle()
                    }
                    .help(L("把文字和文件路径保存到本机，重启后还在；图片不保存"))
                    headerButton(L("清空"), "trash") { store.clear() }
                        .help(L("置顶内容不会被清空"))
                }
            }
            Card(padding: 6) {
                if filtered.isEmpty {
                    Text(store.isPaused ? L("已暂停记录") : (query.isEmpty ? L("复制的内容会出现在这里，点一下即可重新复制") : L("没有匹配的内容")))
                        .font(.system(size: 12))
                        .foregroundStyle(Theme.secondary)
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    ScrollView(.vertical) {
                        LazyVGrid(columns: [GridItem(.flexible(), spacing: 6), GridItem(.flexible(), spacing: 6)], spacing: 2) {
                            ForEach(filtered) { item in
                                ClipboardRow(item: item, onPin: { store.togglePin(item) }) {
                                    store.copy(item)
                                    AppDelegate.shared.closePanel()
                                }
                                .contextMenu {
                                    if case .image = item.content {
                                        Button(L("提取文字")) { store.copyText(in: item) }
                                    }
                                    Button(item.isPinned ? L("取消置顶") : L("置顶")) { store.togglePin(item) }
                                    Button(L("删除")) { store.remove(item) }
                                }
                            }
                        }
                    }
                    .scrollIndicators(.never)
                }
            }
        }
    }
}

struct ClipboardCard: View {
    @ObservedObject var model: PanelModel
    @ObservedObject private var store = ClipboardStore.shared

    var body: some View {
        Card {
            VStack(alignment: .leading, spacing: 4) {
                Button { model.page = .clipboard } label: {
                    HStack(spacing: 5) {
                        Image(systemName: "doc.on.clipboard").foregroundStyle(Theme.blue)
                        Text(L("剪贴板")).font(.system(size: 13, weight: .semibold)).lineLimit(1).minimumScaleFactor(0.8)
                        Spacer()
                        Image(systemName: "chevron.right").font(.system(size: 10)).foregroundStyle(Theme.tertiary)
                    }
                    .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                if store.items.isEmpty {
                    Text(L("暂无内容"))
                        .font(.system(size: 12))
                        .foregroundStyle(Theme.secondary)
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    VStack(spacing: 0) {
                        ForEach(store.items.prefix(3)) { item in
                            ClipboardRow(item: item, showsMeta: false) { store.copy(item) }
                        }
                    }
                    Spacer(minLength: 0)
                }
            }
        }
    }
}
