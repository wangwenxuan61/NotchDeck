import AppKit
import CoreImage
import ImageIO
import SwiftUI
import Vision

/// 历史默认保存到本机，重启后还在；关掉“保存历史”后只保存置顶的内容。图片存成单独的文件。
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    enum Content {
        case text(String)
        /// 列表只显示缩略图，原图数据只在复制、查看和识别文字时用，不常驻解码后的大图。
        case image(thumbnail: NSImage, data: Data, type: NSPasteboard.PasteboardType, size: CGSize)
        case files([URL])
    }

    /// 点击时复制成什么样：原样（带格式）、纯文本，或者只保留结构的干净格式。
    enum CopyStyle {
        case original, plain, clean
    }

    struct Item: Identifiable {
        let id: UUID
        let content: Content
        var date: Date
        let sourceName: String
        var isPinned = false
        /// 文字附带的格式（HTML、RTF），没有格式时为 nil。
        let rich: RichText?
        var hasFormatting: Bool { rich != nil }
        /// 只有展示和搜索用这段，复制时始终使用完整内容。
        private let textPreview: String
        private static let previewLength = 20_000

        init(id: UUID = UUID(), content: Content, date: Date, sourceName: String, isPinned: Bool = false, rich: RichText? = nil) {
            self.id = id
            self.content = content
            self.date = date
            self.sourceName = sourceName
            self.isPinned = isPinned
            self.rich = rich.flatMap { $0.isEmpty ? nil : $0 }
            if case .text(let text) = content {
                textPreview = String(text.trimmingCharacters(in: .whitespacesAndNewlines).prefix(Self.previewLength))
            } else {
                textPreview = ""
            }
        }

        var preview: String {
            switch content {
            case .text: return textPreview
            case .image(_, _, _, let size): return L("图片 %d×%d", Int(size.width), Int(size.height))
            case .files(let urls):
                let first = urls.first?.lastPathComponent ?? ""
                return urls.count > 1 ? L("%@ 等 %d 个文件", first, urls.count) : first
            }
        }
    }

    private static let maxItems = 60
    private static let maxImages = 12
    private static let maxImageBytes = 8_000_000
    /// 超过这个大小的文字不记录。历史里的内容必须能完整粘贴回去，所以不做截断。
    private static let maxTextBytes = 1_000_000
    /// 格式数据超过这个大小时只保留文字，避免很大的网页占满内存。
    private static let maxRichBytes = 1_000_000
    /// 密码管理器等 App 用这些类型标记不应被记录的内容。
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
    ]

    private static let saveHistoryKey = "clipboardSaveHistory"
    private static let copyPlainKey = "clipboardCopyPlain"
    /// 自动更新重启时临时保存了全部历史，新版本读回后要按设置重写文件。
    private static let keptForRestartKey = "clipboardKeptForRestart"

    private struct SavedItem: Codable {
        let id: UUID
        var text: String?
        var paths: [String]?
        let date: Date
        let sourceName: String
        let isPinned: Bool
        /// 旧版本保存的文件里没有这几项，读出来是 nil。
        var rtf: Data?
        var html: Data?
        /// 图片存在 imageFolder 里，这里只记文件名和类型。
        var image: String?
        var imageType: String?

        init(_ item: Item) {
            switch item.content {
            case .text(let value):
                text = value
                rtf = item.rich?.rtf
                html = item.rich?.html
            case .files(let urls): paths = urls.map(\.path)
            case .image(_, _, let type, _):
                image = item.id.uuidString
                imageType = type.rawValue
            }
            id = item.id
            date = item.date
            sourceName = item.sourceName
            isPinned = item.isPinned
        }

        var item: Item? {
            let content: Content
            if let text {
                content = .text(text)
            } else if let paths {
                content = .files(paths.map { URL(fileURLWithPath: $0) })
            } else if let image, let imageType, let data = try? Data(contentsOf: ClipboardStore.imageFolder.appendingPathComponent(image)),
                      let loaded = ClipboardStore.imageContent(data, type: NSPasteboard.PasteboardType(imageType)) {
                content = loaded
            } else {
                return nil
            }
            return Item(id: id, content: content, date: date, sourceName: sourceName, isPinned: isPinned, rich: RichText(rtf: rtf, html: html))
        }
    }

    @Published private(set) var items: [Item] = [] {
        didSet {
            schedulePersist()
            let ids = Set(items.map(\.id))
            suggestionCache = suggestionCache.filter { ids.contains($0.key) }
            if imageText.keys.contains(where: { !ids.contains($0) }) { imageText = imageText.filter { ids.contains($0.key) } }
        }
    }
    /// 在本机从图片里识别出的文字，用于搜索、查看和提取文字。
    @Published private(set) var imageText: [UUID: String] = [:]
    private var analyzing: Set<UUID> = []
    /// 每条文字的整理建议只算一次。
    private(set) var suggestionCache: [UUID: [Suggestion]] = [:]
    @Published var isPaused = false
    /// 点击带格式的内容时默认复制成纯文本；按住 ⇧ 点击复制成另一种。
    @Published var copiesPlainByDefault: Bool {
        didSet { UserDefaults.standard.set(copiesPlainByDefault, forKey: Self.copyPlainKey) }
    }
    @Published var saveHistory: Bool {
        didSet {
            UserDefaults.standard.set(saveHistory, forKey: Self.saveHistoryKey)
            schedulePersist()
        }
    }

    /// 检查程序会换成一个独立的剪贴板，免得改动用户正在用的系统剪贴板。
    var pasteboard = NSPasteboard.general
    private let fileURL = Storage.folder.appendingPathComponent("clipboard.json")
    private var lastChange: Int
    private var timer: Timer?
    private var persistWork: DispatchWorkItem?
    private var keepAllForRestart = false
    /// 写文件在后台排队进行，带格式的历史可能有几 MB，不能卡住界面。
    private let saveQueue = DispatchQueue(label: "notchdeck.clipboard.save", qos: .utility)
    private let suggestionQueue = DispatchQueue(label: "notchdeck.clipboard.suggestions", qos: .utility)
    /// 识别图片单独排队：第一次识别要等系统准备模型，不能拖住文字的整理推荐。
    private let imageQueue = DispatchQueue(label: "notchdeck.clipboard.images", qos: .utility)

    private init() {
        lastChange = NSPasteboard.general.changeCount
        // 没设置过时默认保存，重启后历史还在。
        saveHistory = UserDefaults.standard.object(forKey: Self.saveHistoryKey) as? Bool ?? true
        copiesPlainByDefault = UserDefaults.standard.bool(forKey: Self.copyPlainKey)
        if let data = try? Data(contentsOf: fileURL), let saved = try? JSONDecoder().decode([SavedItem].self, from: data) {
            items = saved.compactMap(\.item)
            prepareSuggestions(for: items)
            items.forEach(analyze)
        }
        if UserDefaults.standard.bool(forKey: Self.keptForRestartKey) {
            UserDefaults.standard.removeObject(forKey: Self.keptForRestartKey)
            persistNow()
        }
    }

    /// 自动更新重启前调用：没开“保存历史”时也把这次的历史留到新版本，读回后立即只保留固定的项。
    func persistForRestart() {
        if !saveHistory {
            keepAllForRestart = true
            UserDefaults.standard.set(true, forKey: Self.keptForRestartKey)
        }
        persistNow()
    }

    private func schedulePersist() {
        persistWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            let snapshot = self.snapshot, url = self.fileURL
            self.saveQueue.async { Self.write(snapshot, to: url) }
        }
        persistWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    /// 立即保存并等写完，退出和更新重启前用。
    func persistNow() {
        persistWork?.cancel()
        persistWork = nil
        let snapshot = snapshot, url = fileURL
        saveQueue.sync { Self.write(snapshot, to: url) }
    }

    private struct Snapshot {
        var items: [SavedItem] = []
        var images: [String: Data] = [:]
    }

    private static let imageFolder = Storage.folder.appendingPathComponent("ClipboardImages", isDirectory: true)

    private var snapshot: Snapshot {
        var result = Snapshot()
        for item in items where saveHistory || keepAllForRestart || item.isPinned {
            let saved = SavedItem(item)
            result.items.append(saved)
            if case .image(_, let data, _, _) = item.content, let name = saved.image { result.images[name] = data }
        }
        return result
    }

    private static func write(_ snapshot: Snapshot, to url: URL) {
        let manager = FileManager.default
        // 图片的内容不会变，已经存过的不再重写；不在历史里的删掉。
        let existing = Set((try? manager.contentsOfDirectory(atPath: imageFolder.path)) ?? [])
        for name in existing.subtracting(snapshot.images.keys) { try? manager.removeItem(at: imageFolder.appendingPathComponent(name)) }
        if !snapshot.images.isEmpty {
            try? manager.createDirectory(at: imageFolder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        }
        for (name, data) in snapshot.images where !existing.contains(name) {
            let file = imageFolder.appendingPathComponent(name)
            try? data.write(to: file, options: .atomic)
            try? manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        }
        guard !snapshot.items.isEmpty else {
            try? manager.removeItem(at: url)
            return
        }
        guard let data = try? JSONEncoder().encode(snapshot.items) else { return }
        try? data.write(to: url, options: .atomic)
        // 复制的内容可能敏感，文件只允许当前用户读写。
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    func start() {
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard !isPaused, let content = readContent() else { return }
        let app = NSWorkspace.shared.frontmostApplication
        insert(Item(content: content, date: Date(), sourceName: app?.localizedName ?? "", rich: readRichText(for: content)))
    }

    private func readContent() -> Content? {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return nil }

        let fileOptions: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: fileOptions) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return text.utf8.count <= Self.maxTextBytes ? .text(text) : nil
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes, let content = Self.imageContent(data, type: type) {
                return content
            }
        }
        return nil
    }

    /// 只解码出一张小缩略图，原图保持压缩数据，避免十几张截图占掉上百 MB 内存。
    static func imageContent(_ data: Data, type: NSPasteboard.PasteboardType) -> Content? {
        thumbnail(of: data).map { .image(thumbnail: $0.0, data: data, type: type, size: $0.1) }
    }

    static func thumbnail(of data: Data) -> (NSImage, CGSize)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int,
              let image = downsample(data, maxPixels: 128) else { return nil }
        return (NSImage(cgImage: image, size: .zero), CGSize(width: width, height: height))
    }

    static func downsample(_ data: Data, maxPixels: Int) -> CGImage? {
        CGImageSourceCreateWithData(data as CFData, nil).flatMap {
            CGImageSourceCreateThumbnailAtIndex($0, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: maxPixels,
            ] as CFDictionary)
        }
    }

    static func fullImage(_ data: Data) -> CGImage? {
        CGImageSourceCreateWithData(data as CFData, nil).flatMap { CGImageSourceCreateImageAtIndex($0, 0, nil) }
    }

    /// 文字附带的格式。太大时不保存格式，只留文字。
    private func readRichText(for content: Content) -> RichText? {
        guard case .text = content else { return nil }
        let rich = RichText(rtf: pasteboard.data(forType: .rtf), html: pasteboard.data(forType: .html))
        guard !rich.isEmpty, rich.byteCount <= Self.maxRichBytes else { return nil }
        return rich
    }

    /// 新内容排在置顶项之后。
    private var insertionIndex: Int { items.firstIndex { !$0.isPinned } ?? items.endIndex }

    func insert(_ item: Item) {
        func matches(_ other: Item) -> Bool { Self.isSameContent(other.content, item.content) }
        guard !items.contains(where: { $0.isPinned && matches($0) }) else { return }
        items.removeAll(where: matches)
        items.insert(item, at: insertionIndex)
        trim()
        prepareSuggestions(for: [item])
        analyze(item)
    }

    /// 图片进来就在后台识别文字，之后可以按图里的文字搜索。
    func analyze(_ item: Item) {
        guard case .image(_, let data, _, _) = item.content, imageText[item.id] == nil, analyzing.insert(item.id).inserted else { return }
        imageQueue.async { [weak self] in
            let text = Self.fullImage(data).flatMap(Self.recognizeText) ?? ""
            DispatchQueue.main.async {
                guard let self else { return }
                self.analyzing.remove(item.id)
                if self.items.contains(where: { $0.id == item.id }) { self.imageText[item.id] = text }
            }
        }
    }

    /// 在后台提前算好整理推荐，打开右键菜单时直接用。
    private func prepareSuggestions(for items: [Item]) {
        let texts = items.compactMap { item -> (UUID, String, String)? in
            guard case .text(let text) = item.content, suggestionCache[item.id] == nil else { return nil }
            return (item.id, text, item.sourceName)
        }
        guard !texts.isEmpty else { return }
        suggestionQueue.async { [weak self] in
            let found = texts.map { ($0.0, TextTransforms.suggestions(for: $0.1, source: $0.2)) }
            DispatchQueue.main.async {
                guard let self else { return }
                let present = Set(self.items.map(\.id))
                for (id, suggestions) in found where present.contains(id) { self.suggestionCache[id] = suggestions }
            }
        }
    }

    static func isSameContent(_ first: Content, _ second: Content) -> Bool {
        switch (first, second) {
        case (.text(let a), .text(let b)): return a == b
        case (.image(_, let a, _, _), .image(_, let b, _, _)): return a == b
        case (.files(let a), .files(let b)): return a.map(\.path) == b.map(\.path)
        default: return false
        }
    }

    /// 数量上限只约束未置顶的内容。
    private func trim() {
        var imageCount = 0
        items.removeAll {
            guard !$0.isPinned, case .image = $0.content else { return false }
            imageCount += 1
            return imageCount > Self.maxImages
        }
        let overflow = items.filter { !$0.isPinned }.count - Self.maxItems
        if overflow > 0 { items.removeLast(overflow) }
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        items = items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    /// 点击时的默认复制方式；inverted 为 true（按住 ⇧）时用另一种。
    func defaultStyle(inverted: Bool = false) -> CopyStyle {
        copiesPlainByDefault != inverted ? .plain : .original
    }

    func copy(_ item: Item, style requested: CopyStyle? = nil) {
        let style = requested ?? defaultStyle()
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): write(text, rich: item.rich, style: style)
        case .image(_, let data, let type, _): pasteboard.setData(data, forType: type)
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        lastChange = pasteboard.changeCount
        // 重新复制的内容排到最上面，时间也改成现在，顺序和时间才对得上。
        var copied = item
        copied.date = Date()
        items.removeAll { $0.id == item.id }
        items.insert(copied, at: item.isPinned ? 0 : insertionIndex)
        // 没有格式的内容不管选哪种都一样，提示保持“已复制”。
        let message = !item.hasFormatting || style == .original ? L("已复制") : (style == .plain ? L("已复制为纯文本") : L("已复制为干净格式"))
        Toasts.shared.show(message, icon: "doc.on.clipboard")
    }

    private func write(_ text: String, rich: RichText?, style: CopyStyle) {
        switch style {
        case .original:
            if let rtf = rich?.rtf { pasteboard.setData(rtf, forType: .rtf) }
            if let html = rich?.html { pasteboard.setData(html, forType: .html) }
        case .clean:
            if let rich, let html = RichTextCleaner.cleanHTML(from: rich) { pasteboard.setData(Data(html.utf8), forType: .html) }
        case .plain:
            break
        }
        pasteboard.setString(text, forType: .string)
    }

    func suggestions(for item: Item) -> [Suggestion] {
        guard case .text(let text) = item.content else { return [] }
        if let cached = suggestionCache[item.id] { return cached }
        let found = TextTransforms.suggestions(for: text, source: item.sourceName)
        suggestionCache[item.id] = found
        return found
    }

    /// 复制整理后的文字，并作为一条新记录放进历史，原来那条保留。
    func copy(_ suggestion: Suggestion, from item: Item) {
        copyDerived(.text(suggestion.result), from: item)
        Toasts.shared.show(L("已复制整理后的内容"), icon: "wand.and.stars")
    }

    /// 由一条记录得到的新内容（整理结果、识别出的文字、抠出的主体）作为新的一条加入历史并复制，原来那条保留。
    private func copyDerived(_ content: Content, from item: Item) {
        let derived = Item(content: content, date: Date(), sourceName: item.sourceName)
        insert(derived)
        copy(derived, style: .plain)
    }

    /// 在本机抠出图片里的主体（人、动物、物品），复制成透明背景的 PNG。
    func copySubject(of item: Item) {
        guard case .image(_, let data, _, _) = item.content else { return }
        DispatchQueue.global(qos: .userInitiated).async {
            let content = Self.fullImage(data).flatMap(Self.liftSubject).flatMap { Self.imageContent($0, type: .png) }
            DispatchQueue.main.async {
                guard let content else {
                    Toasts.shared.show(L("没有找到可以抠出的主体"), icon: "person.and.background.dotted")
                    return
                }
                self.copyDerived(content, from: item)
                Toasts.shared.show(L("已复制抠出的主体"), icon: "person.and.background.dotted")
            }
        }
    }

    static func liftSubject(_ image: CGImage) -> Data? {
        let request = VNGenerateForegroundInstanceMaskRequest()
        let handler = VNImageRequestHandler(cgImage: image)
        guard (try? handler.perform([request])) != nil, let result = request.results?.first, !result.allInstances.isEmpty,
              let buffer = try? result.generateMaskedImage(ofInstances: result.allInstances, from: handler, croppedToInstancesExtent: true),
              let space = CGColorSpace(name: CGColorSpace.sRGB) else { return nil }
        return CIContext().pngRepresentation(of: CIImage(cvPixelBuffer: buffer), format: .RGBA8, colorSpace: space)
    }

    /// 在本机识别图片里的文字并复制，不会上传。复制后会和普通内容一样进入历史。
    func copyText(in item: Item) {
        guard case .image(_, let data, _, _) = item.content else { return }
        if let text = imageText[item.id] { copyRecognized(text, from: item); return }
        DispatchQueue.global(qos: .userInitiated).async {
            let text = Self.fullImage(data).flatMap(Self.recognizeText) ?? ""
            DispatchQueue.main.async { self.copyRecognized(text, from: item) }
        }
    }

    private func copyRecognized(_ text: String, from item: Item) {
        guard !text.isEmpty else {
            Toasts.shared.show(L("没有识别到文字"), icon: "text.viewfinder")
            return
        }
        copyDerived(.text(text), from: item)
        Toasts.shared.show(L("已复制识别出的文字"), icon: "text.viewfinder")
    }

    /// Vision 在主线程上会卡住，只能在后台队列调用。
    static func recognizeText(in image: CGImage) -> String? {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.recognitionLanguages = ["zh-Hans", "zh-Hant", "en-US", "ja-JP", "ko-KR"]
        request.usesLanguageCorrection = true
        guard (try? VNImageRequestHandler(cgImage: image).perform([request])) != nil else { return nil }
        return request.results?.compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }

    func remove(_ item: Item) { items.removeAll { $0.id == item.id } }

    /// 置顶内容不会被清空，要单独取消置顶或删除。
    func clear() { items.removeAll { !$0.isPinned } }
}

struct ClipboardRow: View {
    let item: ClipboardStore.Item
    var showsMeta = true
    var onPin: (() -> Void)?
    let action: () -> Void
    @State private var hovering = false

    /// 首页卡片里只有三行的高度，紧凑模式要用更小的缩略图。
    private var thumbnailSize: CGFloat { showsMeta ? 28 : 20 }

    @ViewBuilder private var thumbnail: some View {
        switch item.content {
        case .text:
            Image(systemName: "text.alignleft").foregroundStyle(Theme.secondary)
        case .image(let thumbnail, _, _, _):
            Image(nsImage: thumbnail).resizable().scaledToFill().frame(width: thumbnailSize, height: thumbnailSize)
                .clipShape(RoundedRectangle(cornerRadius: 5, style: .continuous))
        case .files(let urls):
            Image(nsImage: NSWorkspace.shared.icon(forFile: urls.first?.path ?? "/")).resizable().frame(width: thumbnailSize - 2, height: thumbnailSize - 2)
        }
    }

    var body: some View {
        Button(action: action) {
            HStack(spacing: 8) {
                thumbnail.frame(width: thumbnailSize, height: thumbnailSize)
                VStack(alignment: .leading, spacing: 2) {
                    Text(item.preview.replacingOccurrences(of: "\n", with: " "))
                        .font(.system(size: 12))
                        .lineLimit(1)
                    if showsMeta {
                        HStack(spacing: 5) {
                            Text(item.sourceName.isEmpty ? relativeTime(item.date) : "\(item.sourceName) · \(relativeTime(item.date))")
                                .font(.system(size: 10))
                                .foregroundStyle(Theme.secondary)
                                .lineLimit(1)
                            if item.hasFormatting {
                                // 带格式的内容，点击时按设置复制成原格式或纯文本。
                                Text(verbatim: "Aa")
                                    .font(.system(size: 8, weight: .semibold))
                                    .foregroundStyle(Theme.secondary)
                                    .padding(.horizontal, 3)
                                    .overlay(RoundedRectangle(cornerRadius: 3, style: .continuous).stroke(Theme.tertiary, lineWidth: 0.5))
                                    .help(L("带格式"))
                            }
                        }
                    }
                }
                Spacer(minLength: 0)
            }
            .padding(.leading, 8)
            .padding(.trailing, onPin == nil ? 8 : 30)
            .padding(.vertical, showsMeta ? 4 : 2)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(hovering ? Theme.controlHover : Color.clear))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .overlay(alignment: .trailing) {
            if let onPin, hovering || item.isPinned {
                Button(action: onPin) {
                    Image(systemName: item.isPinned ? "pin.fill" : "pin")
                        .font(.system(size: 11))
                        .foregroundStyle(item.isPinned ? Theme.orange : Theme.secondary)
                        .frame(width: 24, height: 24)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .padding(.trailing, 4)
                .help(item.isPinned ? L("取消置顶") : L("置顶"))
            }
        }
        .onHover { hovering = $0 }
    }
}

struct ClipboardPage: View {
    @ObservedObject var model: PanelModel
    @ObservedObject private var store = ClipboardStore.shared
    @State private var query = ""
    @State private var viewingID: UUID?

    private var viewing: ClipboardStore.Item? {
        viewingID.flatMap { id in store.items.first { $0.id == id } }
    }

    private var filtered: [ClipboardStore.Item] {
        let trimmed = query.trimmingCharacters(in: .whitespaces)
        guard !trimmed.isEmpty else { return store.items }
        // 图片按识别出的文字搜索。
        return store.items.filter {
            $0.preview.localizedCaseInsensitiveContains(trimmed) || store.imageText[$0.id]?.localizedCaseInsensitiveContains(trimmed) == true
        }
    }

    /// 先列出认出来的整理方式（最多 3 项，其余放进“更多整理”），再列格式和其他操作。
    @ViewBuilder private func menu(for item: ClipboardStore.Item) -> some View {
        let suggestions = store.suggestions(for: item)
        let apply = { (suggestion: Suggestion) in
            Button { store.copy(suggestion, from: item); AppDelegate.shared.closePanel() } label: {
                Label(suggestion.title, systemImage: "wand.and.stars")
            }
        }
        ForEach(suggestions.prefix(3), content: apply)
        if suggestions.count > 3 {
            Menu(L("更多整理")) { ForEach(suggestions.dropFirst(3), content: apply) }
        }
        if !suggestions.isEmpty { Divider() }
        if item.hasFormatting {
            Button(L("复制原格式")) { copy(item, .original) }
            Button(L("复制为纯文本")) { copy(item, .plain) }
            Button(L("复制为干净格式")) { copy(item, .clean) }
            Divider()
        }
        Button(L("查看")) { viewingID = item.id }
        if case .image = item.content {
            if store.imageText[item.id]?.isEmpty != true {
                Button(L("提取文字")) { store.copyText(in: item) }
            }
            Button(L("抠出主体")) { store.copySubject(of: item) }
        }
        Button(item.isPinned ? L("取消置顶") : L("置顶")) { store.togglePin(item) }
        Button(L("删除")) { store.remove(item) }
    }

    private func copy(_ item: ClipboardStore.Item, _ style: ClipboardStore.CopyStyle) {
        store.copy(item, style: style)
        AppDelegate.shared.closePanel()
    }

    private func headerButton(_ title: String, _ symbol: String, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Label(title, systemImage: symbol).font(.system(size: 12))
        }
        .buttonStyle(.plain)
    }

    var body: some View {
        if let viewing {
            VStack(spacing: 6) {
                PageHeader(title: L("剪贴板"), model: model, back: { viewingID = nil }) {
                    HStack(spacing: 12) {
                        headerButton(L("复制"), "doc.on.doc") {
                            store.copy(viewing, style: store.defaultStyle(inverted: false))
                            AppDelegate.shared.closePanel()
                        }
                        headerButton(L("删除"), "trash") { store.remove(viewing) }
                    }
                }
                Card(padding: 10) { ClipboardDetail(item: viewing) }
            }
        } else {
            list
        }
    }

    private var list: some View {
        VStack(spacing: 6) {
            PageHeader(title: L("剪贴板"), model: model) {
                HStack(spacing: 12) {
                    HStack(spacing: 4) {
                        Image(systemName: "magnifyingglass").font(.system(size: 11)).foregroundStyle(Theme.secondary)
                        TextField(L("搜索"), text: $query).textFieldStyle(.plain).font(.system(size: 12))
                    }
                    .padding(.horizontal, 8)
                    .frame(width: 170, height: 20)
                    .background(Capsule().fill(Theme.control))
                    headerButton(store.isPaused ? L("继续记录") : L("暂停记录"), store.isPaused ? "play.fill" : "pause.fill") {
                        store.isPaused.toggle()
                    }
                    headerButton(L("保存历史"), store.saveHistory ? "checkmark.circle.fill" : "circle") {
                        store.saveHistory.toggle()
                    }
                    .help(L("把剪贴板历史（包括图片）保存到本机，重启后还在；关掉后只保存置顶的内容"))
                    headerButton(L("清空"), "trash") { store.clear() }
                        .help(L("置顶内容不会被清空"))
                }
            }
            Card(padding: 6) {
                if filtered.isEmpty {
                    Text(store.isPaused ? L("已暂停记录") : (query.isEmpty ? L("复制的内容会出现在这里，点一下即可重新复制") : L("没有匹配的内容")))
                        .font(.system(size: 12))
                        .foregroundStyle(Theme.secondary)
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else {
                    ScrollView(.vertical) {
                        LazyVGrid(columns: [GridItem(.flexible(), spacing: 6), GridItem(.flexible(), spacing: 6)], spacing: 2) {
                            ForEach(filtered) { item in
                                ClipboardRow(item: item, onPin: { store.togglePin(item) }) {
                                    // 按住 ⇧ 点击时复制成另一种：默认原格式就复制纯文本，默认纯文本就复制原格式。
                                    store.copy(item, style: store.defaultStyle(inverted: NSEvent.modifierFlags.contains(.shift)))
                                    AppDelegate.shared.closePanel()
                                }
                                .contextMenu { menu(for: item) }
                            }
                        }
                    }
                    .scrollIndicators(.never)
                }
            }
        }
    }
}

/// 查看一条记录的完整内容：文字可以选中复制，图片显示大图和识别出的文字，文件列出完整路径。
struct ClipboardDetail: View {
    let item: ClipboardStore.Item
    @ObservedObject private var store = ClipboardStore.shared
    @State private var image: NSImage?
    /// 很长的文字只显示开头，渲染不会卡住；复制时仍是完整内容。
    private static let shownLength = 50_000

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            Text(meta).font(.system(size: 10)).foregroundStyle(Theme.secondary)
            switch item.content {
            case .text(let text):
                selectableText(String(text.prefix(Self.shownLength)) + (text.count > Self.shownLength ? "\n…" : ""))
            case .image(let thumbnail, let data, _, _):
                HStack(alignment: .top, spacing: 10) {
                    Image(nsImage: image ?? thumbnail).resizable().scaledToFit()
                        .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                    recognized.frame(maxWidth: .infinity, maxHeight: .infinity)
                }
                .task(id: item.id) {
                    store.analyze(item)
                    await load(data)
                }
            case .files(let urls):
                ScrollView(.vertical) {
                    VStack(alignment: .leading, spacing: 4) {
                        ForEach(urls, id: \.self) { url in
                            Button { NSWorkspace.shared.activateFileViewerSelecting([url]) } label: {
                                HStack(spacing: 6) {
                                    Image(nsImage: NSWorkspace.shared.icon(forFile: url.path)).resizable().frame(width: 16, height: 16)
                                    Text(url.path).font(.system(size: 12)).lineLimit(1).truncationMode(.middle)
                                }
                                .contentShape(Rectangle())
                            }
                            .buttonStyle(.plain)
                            .help(L("在访达中显示"))
                        }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                }
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
    }

    private var meta: String {
        var parts = [item.sourceName, relativeTime(item.date)].filter { !$0.isEmpty }
        switch item.content {
        case .text(let text): parts.append(L("%d 个字", text.count))
        case .image: parts.append(item.preview)
        case .files(let urls): parts.append(L("%d 个文件", urls.count))
        }
        return parts.joined(separator: " · ")
    }

    @ViewBuilder private var recognized: some View {
        if let text = store.imageText[item.id] {
            if text.isEmpty {
                Text(L("没有识别到文字")).font(.system(size: 12)).foregroundStyle(Theme.secondary)
            } else {
                selectableText(text)
            }
        } else {
            // 第一次识别时系统要先准备识字模型，可能要等半分钟，所以写明在做什么。
            VStack(spacing: 6) {
                ProgressView().controlSize(.small)
                Text(L("正在识别文字…")).font(.system(size: 11)).foregroundStyle(Theme.secondary)
            }
        }
    }

    private func selectableText(_ text: String) -> some View {
        ScrollView(.vertical) {
            Text(text).font(.system(size: 12)).textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    /// 大图只解码到面板用得到的尺寸，放在后台解码。
    private func load(_ data: Data) async {
        let shown = await withCheckedContinuation { continuation in
            DispatchQueue.global(qos: .userInitiated).async { continuation.resume(returning: ClipboardStore.downsample(data, maxPixels: 1200)) }
        }
        image = shown.map { NSImage(cgImage: $0, size: .zero) }
    }
}

